# Build Tier_DD (delay-difference EM) test inputs in "Inputs DD/" for the
# single-stock SESSF operating models, by copying each stock's OM, EM and
# general file and
#   * switching the EM to Ass_Basic:Type Tier_DD and appending a #Tier_DD:
#     block whose priors are derived from the OM biology (growth, M, h);
#   * picking the CPUE index (fleet with future index data and the most past
#     years) and the length fleet (fleet with future retained length data and
#     the most past years);
#   * setting 1 simulation, 10 projection years, an assessment every 3 years.
# The derivation reproduces the hand-set Morwong values (Rho 0.79, Surv 0.861,
# Tauk 21.45, Linf 35.5, Sigtau 3, MaxLen_g1 26, beta 0.893), apart from
# rounding.  Run from the repository root:
#   Rscript "MISC HCR/make_DD_inputs.R"
# Morwong is not regenerated (its hand-set file is kept).

Stocks <- list(
  Bight.redfish      = "Inputs CSIRO/",
  Blue.grenadier     = "Inputs CSIRO/",
  Deepwater.flathead = "Inputs CSIRO/",
  Mirror.dory        = "Inputs CSIRO/",
  Orange.roughy.east = "Inputs CSIRO/",
  Pink.ling          = "Inputs CSIRO/",
  Tiger.flathead     = "Inputs CSIROM/",
  School.whiting     = "Inputs CSIROM/",
  Silver.warehou     = "Inputs Buffer/")
OutDir <- "Inputs DD/"

rd <- function(f) sub("\r$", "", readLines(f, warn=FALSE))
wr <- function(x, f) writeBin(charToRaw(paste0(paste(x, collapse="\r\n"), "\r\n")), f)  # keep CRLF
num <- function(s) suppressWarnings(as.numeric(strsplit(trimws(s), "[[:space:]]+")[[1]]))
after <- function(L, key, n=1) { i <- which(startsWith(L, key))[1]; if (is.na(i)) stop("not found: ", key); L[i + seq_len(n)] }

# count of past years with data (> 0) by fleet in a "Frequency_past" table
past_count <- function(L, key) {
  i <- which(startsWith(L, key))[1] + 1
  rows <- c()
  while (i <= length(L) && grepl("^[0-9]{4} ", L[i])) { rows <- rbind(rows, num(L[i])); i <- i + 1 }
  colSums(rows[, -1, drop=FALSE] > 0)
}

Summary <- NULL
for (St in names(Stocks)) {
  Src <- Stocks[[St]]
  OM <- rd(paste0(Src, St, ".OM"))
  Nsex <- num(after(OM, "# Number of sexes"))[1]
  M    <- num(after(OM, "# Base M", Nsex)[1])[1]
  Aminmax <- num(after(OM, "#Growth:min/max age"))
  # first sex (female in SS) only: sexes can differ a lot (Mirror dory k 0.19 / 1.01)
  L1 <- num(after(OM, "#Growth:L_at_Amin"))[1]
  L2 <- num(after(OM, "#Growth:L_at_Amax"))[1]
  k  <- num(after(OM, "#Growth:k by sex"))[1]
  CV <- mean(c(num(after(OM, "#Growth:CV1"))[1], num(after(OM, "#Growth:CV2"))[1]))
  h  <- num(sub("#SR:Steepness", "", OM[startsWith(OM, "#SR:Steepness")]))[1]
  A1 <- Aminmax[1]; A2 <- Aminmax[2]
  Linf <- if (A2 >= 999) L2 else (L2 - L1*exp(-k*(A2-A1))) / (1 - exp(-k*(A2-A1)))
  kage <- max(1, round(A1))
  Tauk <- Linf + (L1 - Linf)*exp(-k*(kage - A1))
  Sigtau <- CV * (Tauk + Linf)/2
  MaxLen <- Tauk + (Linf - Tauk)/3
  beta <- max(0.05, (1 - 0.2/h)/0.8)

  # CPUE index and length fleet
  IsIdx <- strsplit(trimws(after(OM, "#Index:Is_index")), "[[:space:]]+")[[1]] == "Yes"
  FutIdx <- num(after(OM, "#Index:Frequency_future"))
  PastIdx <- past_count(OM, "#Index:Frequency_past")
  okI <- which(IsIdx & FutIdx > 0)
  if (length(okI) == 0) okI <- which(IsIdx)
  Cpue <- okI[which.max(PastIdx[okI])]
  IsLen <- strsplit(trimws(after(OM, "#Length:Is_length")), "[[:space:]]+")[[1]] == "Yes"
  FutLen <- num(after(OM, "#Length:Frequency_future", 3)[1])        # retained row
  PastRet <- past_count(OM, "#Length:Frequency_past_retained")
  PastTot <- past_count(OM, "#Length:Frequency_past_total")
  FutTot <- num(after(OM, "#Length:Frequency_future", 3)[3])
  okL <- which(IsLen & FutLen > 0 & PastRet > 0)
  if (length(okL) > 0) { LenF <- okL[which.max(PastRet[okL])]; Part <- 2; Npast <- PastRet[LenF]
  } else { okL <- which(IsLen & FutTot > 0)
    if (length(okL) > 0) { LenF <- okL[which.max(PastTot[okL])]; Part <- 0; Npast <- PastTot[LenF]
    } else { LenF <- 1; Part <- 0; Npast <- 0 } }       # no length data (e.g. orange roughy)

  r <- function(x, d=3) format(signif(x, d))
  Block <- c("",
    "# Tier DD (delay-difference) specifications; generated by MISC HCR/make_DD_inputs.R from the OM biology",
    paste0("#Tier_DD:Cpue_Area 1"),
    paste0("#Tier_DD:Cpue_Index ", Cpue, "             # ", PastIdx[Cpue], " past index years"),
    paste0("#Tier_DD:Len_Area 1"),
    paste0("#Tier_DD:Len_Fleet ", LenF, "              # ", Npast, " past comps"),
    paste0("#Tier_DD:Len_Part ", Part, "               # 2 = retained, 0 = total"),
    "#Tier_DD:MaxNsamp 1000",
    paste0("#Tier_DD:kage ", kage),
    "#Tier_DD:Amax 100",
    "#Tier_DD:gamma_sr 1",
    paste0("#Tier_DD:beta_init ", r(beta), "         # BH, h = ", h),
    "#Tier_DD:EstBeta No",
    "#Tier_DD:sigmaC 0.05",
    "#Tier_DD:sigmaE 0.3",
    "#Tier_DD:sigmaR 0.7",
    "#Tier_DD:lamM 0",
    "#Tier_DD:lamL 1 1 1 1",
    paste0("#Tier_DD:Rho ", r(exp(-k)), " 0.05        # exp(-k), k = ", r(k)),
    paste0("#Tier_DD:Surv ", r(exp(-M)), " 0.03       # exp(-M), M = ", r(M)),
    "#Tier_DD:Entry 0.4 0.15",
    paste0("#Tier_DD:Tauk ", r(Tauk), " ", r(0.07*Tauk, 2), "     # length at age ", kage),
    paste0("#Tier_DD:Linf_init ", r(Linf)),
    "#Tier_DD:EstLinf Yes",
    paste0("#Tier_DD:Sigtau ", r(Sigtau, 2), "             # CV ", r(CV, 2), " at mid length"),
    "#Tier_DD:Q2 0 0.5",
    "#Tier_DD:EstQ2 No",
    "#Tier_DD:Q1sd -1",
    paste0("#Tier_DD:MaxLen_g1 ", r(MaxLen)),
    "#Tier_DD:lamPen 100",
    "#Tier_DD:B0_init_mult 10",
    "#Tier_DD:RecDevLead 3",
    "#Tier_DD:Dlim 0.2                 # PLACEHOLDER HCR on fishable-biomass depletion",
    "#Tier_DD:Dtarg 0.48",
    "#Tier_DD:Htarg 0.1")

  EM <- rd(paste0(Src, St, ".EM"))
  it <- which(grepl("^#Ass_Basic:Type", EM))
  EM[it] <- paste0("#", EM[it])
  EM <- append(EM, "#Ass_Basic:Type Tier_DD   (Fournier-Doonan delay-difference, R Inserts/DelayDiff.R)", after=it[1]-1)
  wr(c(EM, Block), paste0(OutDir, St, ".EM"))
  file.copy(paste0(Src, St, ".OM"), paste0(OutDir, St, ".OM"), overwrite=TRUE)

  G <- rd(paste0(Src, "General_", St, ".OM"))
  G[which(startsWith(G, "#Number_of_simulations"))] <- "#Number_of_simulations 1"
  G[which(startsWith(G, "#Number_of_projection_years"))] <- "#Number_of_projection_years 10"
  ia <- which(startsWith(G, "#Assessment_frequency")); G[ia+1] <- " 3"
  wr(G, paste0(OutDir, "General_", St, ".OM"))

  Summary <- rbind(Summary, data.frame(Stock=St, Source=Src, Nsex=Nsex, M=M, k=signif(k,3),
    Linf=signif(Linf,3), kage=kage, Tauk=signif(Tauk,3), Sigtau=signif(Sigtau,2), h=h,
    Cpue_Index=Cpue, Len_Fleet=LenF, Len_Part=Part, NlenPast=Npast))
}
print(Summary, row.names=FALSE)
